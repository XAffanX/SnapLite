use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct WindowMeta {
    pub id: String,
    pub title: String,
    pub app_name: String,
    pub width: u32,
    pub height: u32,
}

#[cfg(target_os = "windows")]
pub fn list_windows() -> Vec<WindowMeta> {
    use windows::Win32::Foundation::{BOOL, HWND, LPARAM};
    use windows::Win32::UI::WindowsAndMessaging::{
        EnumWindows, GetWindowRect, GetWindowTextW, IsWindowVisible,
    };

    let mut list: Vec<WindowMeta> = Vec::new();

    unsafe extern "system" fn enum_proc(hwnd: HWND, lparam: LPARAM) -> BOOL {
        let list_ptr = lparam.0 as *mut Vec<WindowMeta>;
        let list = &mut *list_ptr;

        if IsWindowVisible(hwnd).as_bool() {
            let mut buf = [0u16; 512];
            let len = GetWindowTextW(hwnd, &mut buf);
            if len > 0 {
                let title = String::from_utf16_lossy(&buf[..len as usize]);
                if !title.trim().is_empty() && title != "Program Manager" && title != "SnapLite" {
                    let mut rect = windows::Win32::Foundation::RECT::default();
                    if GetWindowRect(hwnd, &mut rect).is_ok() {
                        let w = (rect.right - rect.left).max(0) as u32;
                        let h = (rect.bottom - rect.top).max(0) as u32;
                        if w > 100 && h > 100 {
                            list.push(WindowMeta {
                                id: format!("{}", hwnd.0 as usize),
                                title,
                                app_name: "Desktop Application".to_string(),
                                width: w,
                                height: h,
                            });
                        }
                    }
                }
            }
        }
        BOOL(1)
    }

    unsafe {
        let ptr = &mut list as *mut Vec<WindowMeta> as isize;
        let _ = EnumWindows(Some(enum_proc), LPARAM(ptr));
    }

    list
}

#[cfg(not(target_os = "windows"))]
pub fn list_windows() -> Vec<WindowMeta> {
    Vec::new()
}

#[cfg(target_os = "windows")]
pub fn capture_window_by_id(id: &str) -> Result<image::RgbaImage, String> {
    use windows::Win32::Foundation::{HWND, RECT};
    use windows::Win32::Graphics::Gdi::{
        BitBlt, CreateCompatibleBitmap, CreateCompatibleDC, DeleteDC, DeleteObject,
        GetDIBits, GetWindowDC, ReleaseDC, SelectObject, BITMAPINFO, BITMAPINFOHEADER,
        BI_RGB, DIB_RGB_COLORS, SRCCOPY,
    };
    use windows::Win32::UI::WindowsAndMessaging::{GetWindowRect, IsWindow};

    // Window IDs are decimal pointer values generated by list_windows().
    let hwnd_value: usize = id.parse().map_err(|_| "Invalid window ID".to_string())?;
    let hwnd = HWND(hwnd_value as *mut _);

    unsafe {
        if !IsWindow(hwnd).as_bool() {
            return Err("Window no longer exists".to_string());
        }

        let mut rect = RECT::default();
        GetWindowRect(hwnd, &mut rect)
            .map_err(|e| format!("Failed to get window bounds: {e}"))?;

        let width_i32 = rect.right - rect.left;
        let height_i32 = rect.bottom - rect.top;
        if width_i32 <= 0 || height_i32 <= 0 {
            return Err("Window has invalid capture dimensions".to_string());
        }
        let width = width_i32 as u32;
        let height = height_i32 as u32;
        let buffer_size = (width as usize)
            .checked_mul(height as usize)
            .and_then(|n| n.checked_mul(4))
            .ok_or_else(|| "Window screenshot buffer size overflow".to_string())?;

        // GetWindowDC captures the complete window area, including its frame.
        let hdc_window = GetWindowDC(hwnd);
        if hdc_window.is_invalid() {
            return Err("GetWindowDC failed".to_string());
        }

        let hdc_mem = CreateCompatibleDC(hdc_window);
        if hdc_mem.is_invalid() {
            ReleaseDC(hwnd, hdc_window);
            return Err("CreateCompatibleDC failed".to_string());
        }

        let hbitmap = CreateCompatibleBitmap(hdc_window, width_i32, height_i32);
        if hbitmap.is_invalid() {
            let _ = DeleteDC(hdc_mem);
            ReleaseDC(hwnd, hdc_window);
            return Err("CreateCompatibleBitmap failed".to_string());
        }

        let old_obj = SelectObject(hdc_mem, hbitmap);
        if old_obj.is_invalid() {
            let _ = DeleteObject(hbitmap);
            let _ = DeleteDC(hdc_mem);
            ReleaseDC(hwnd, hdc_window);
            return Err("SelectObject failed".to_string());
        }

        // Capture and read the bitmap, always releasing GDI handles afterward.
        let mut deselected = false;
        let capture_result = (|| -> Result<Vec<u8>, String> {
            BitBlt(hdc_mem, 0, 0, width_i32, height_i32, hdc_window, 0, 0, SRCCOPY)
                .map_err(|e| format!("BitBlt failed: {e}"))?;

            // A bitmap must not be selected into any DC when GetDIBits reads it.
            SelectObject(hdc_mem, old_obj);
            deselected = true;

            let mut bmi = BITMAPINFO {
                bmiHeader: BITMAPINFOHEADER {
                    biSize: std::mem::size_of::<BITMAPINFOHEADER>() as u32,
                    biWidth: width_i32,
                    biHeight: -height_i32,
                    biPlanes: 1,
                    biBitCount: 32,
                    biCompression: BI_RGB.0,
                    ..Default::default()
                },
                ..Default::default()
            };

            let mut pixels = vec![0u8; buffer_size];
            let lines = GetDIBits(
                hdc_mem,
                hbitmap,
                0,
                height,
                Some(pixels.as_mut_ptr() as *mut _),
                &mut bmi,
                DIB_RGB_COLORS,
            );
            if lines != height as i32 {
                return Err(format!("GetDIBits returned {lines} scan lines; expected {height}"));
            }
            Ok(pixels)
        })();

        // Restore the previous selection if BitBlt returned early.
        if !deselected {
            SelectObject(hdc_mem, old_obj);
        }
        let _ = DeleteObject(hbitmap);
        let _ = DeleteDC(hdc_mem);
        ReleaseDC(hwnd, hdc_window);

        let mut raw_pixels = capture_result?;
        for pixel in raw_pixels.chunks_exact_mut(4) {
            pixel.swap(0, 2); // BGRA -> RGBA
            pixel[3] = 255;
        }

        image::RgbaImage::from_raw(width, height, raw_pixels)
            .ok_or_else(|| "Failed to construct RGBA screenshot".to_string())
    }
}

#[cfg(not(target_os = "windows"))]
pub fn capture_window_by_id(_id: &str) -> Result<image::RgbaImage, String> {
    Err("Window capture is only supported on Windows".to_string())
}
